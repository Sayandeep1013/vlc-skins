// Converts lucide-static SVG icons into WPF path geometries (Themes/Icons.xaml).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const LUCIDE = path.resolve(here, '..', '..', 'node_modules', 'lucide-static', 'icons');
const OUT = path.resolve(here, '..', 'Themes', 'Icons.xaml');

// key -> lucide name
const ICONS = {
  More: 'ellipsis', Minimize: 'minus', Maximize: 'square', Restore: 'copy', Fullscreen: 'scan',
  ExitFullscreen: 'minimize', Close: 'x', Volume: 'volume-2', Muted: 'volume-x', Audio: 'audio-lines',
  Subtitles: 'captions', Settings: 'settings', Queue: 'list', Sort: 'arrow-down-up', Repeat: 'repeat',
  Shuffle: 'shuffle', Add: 'plus', Remove: 'minus', Folder: 'folder-open', File: 'file-video',
  Network: 'radio', Keyboard: 'keyboard', Info: 'info', Quit: 'log-out', Chevron: 'chevron-right',
  Trash: 'trash-2', Speed: 'gauge', Camera: 'camera', Check: 'check', Reset: 'rotate-ccw', Pin: 'pin',
};

const num = (s) => parseFloat(s);
function attrs(tag) {
  const o = {};
  for (const m of tag.matchAll(/([\w-]+)="([^"]*)"/g)) o[m[1]] = m[2];
  return o;
}
function toPath(svg) {
  const parts = [];
  for (const m of svg.matchAll(/<(path|circle|rect|line|polyline|polygon|ellipse)\b([^>]*)\/?>/g)) {
    const [, el, rest] = m;
    const a = attrs(rest);
    if (el === 'path') {
      // A leading relative "m" is absolute in its own path, but would become relative to the
      // previous subpath once concatenated; make it absolute (and keep implicit lineTo pairs relative).
      const m = /^\s*m\s*(-?[\d.]+)[\s,]*(-?[\d.]+)\s*/.exec(a.d);
      if (!m) { parts.push(a.d); continue; }
      const rest = a.d.slice(m[0].length);
      parts.push(`M${m[1]} ${m[2]} ${/^-?[\d.]/.test(rest) ? 'l' : ''}${rest}`);
    }
    else if (el === 'line') parts.push(`M${a.x1} ${a.y1}L${a.x2} ${a.y2}`);
    else if (el === 'polyline' || el === 'polygon') {
      const p = a.points.trim().split(/[\s,]+/);
      let d = `M${p[0]} ${p[1]}`;
      for (let i = 2; i < p.length; i += 2) d += `L${p[i]} ${p[i + 1]}`;
      parts.push(el === 'polygon' ? d + 'Z' : d);
    } else if (el === 'circle' || el === 'ellipse') {
      const cx = num(a.cx), cy = num(a.cy), rx = num(a.r ?? a.rx), ry = num(a.r ?? a.ry);
      parts.push(`M${cx - rx} ${cy}A${rx} ${ry} 0 1 0 ${cx + rx} ${cy}A${rx} ${ry} 0 1 0 ${cx - rx} ${cy}Z`);
    } else if (el === 'rect') {
      const x = num(a.x ?? 0), y = num(a.y ?? 0), w = num(a.width), h = num(a.height), r = num(a.rx ?? 0);
      parts.push(r
        ? `M${x + r} ${y}H${x + w - r}A${r} ${r} 0 0 1 ${x + w} ${y + r}V${y + h - r}A${r} ${r} 0 0 1 ${x + w - r} ${y + h}H${x + r}A${r} ${r} 0 0 1 ${x} ${y + h - r}V${y + r}A${r} ${r} 0 0 1 ${x + r} ${y}Z`
        : `M${x} ${y}H${x + w}V${y + h}H${x}Z`);
    }
  }
  return parts.join(' ');
}

let xaml = `<!-- Generated by tools/gen-icons.mjs from Lucide (ISC). Do not edit by hand. -->
<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"
                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">
`;
for (const [key, name] of Object.entries(ICONS)) {
  let svg = fs.readFileSync(path.join(LUCIDE, `${name}.svg`), 'utf8');
  // The redesign's "player settings" gear has a play glyph instead of the hub.
  if (key === 'Settings') svg = svg.replace(/<circle[^>]*\/>/, '');
  xaml += `  <Geometry x:Key="Icon.${key}">${toPath(svg)}</Geometry>\n`;
}
// Custom glyphs from the redesign.
xaml += `  <Geometry x:Key="Icon.Prev">M6 5V19 M19 5.5V18.5L8.5 12Z</Geometry>
  <Geometry x:Key="Icon.Next">M18 5V19 M5 5.5V18.5L15.5 12Z</Geometry>
  <Geometry x:Key="Icon.Play">M7.5 5.2V18.8L19 12Z</Geometry>
  <Geometry x:Key="Icon.Pause">M7 5H10V19H7Z M14 5H17V19H14Z</Geometry>
  <Geometry x:Key="Icon.GearPlay">M10.4 9.3V14.7L14.8 12Z</Geometry>
</ResourceDictionary>
`;
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, xaml);
console.log('wrote', OUT);
